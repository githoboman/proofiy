import mongoose, { Schema, Document } from 'mongoose';

/**
 * Certificate Interface
 * This is the off-chain cached representation of the On-Chain Provenance Certificate on BOT Chain.
 * It allows fast querying for the frontend without hitting the BOT Chain RPC constantly.
 */
export interface ICertificate extends Document {
  verificationJobId: mongoose.Types.ObjectId;
  assetId: mongoose.Types.ObjectId;
  manifestId: mongoose.Types.ObjectId;
  creatorId: mongoose.Types.ObjectId;
  
  // On-Chain Data References
  botChainNetwork: 'testnet' | 'mainnet';
  stellarNetwork?: 'testnet' | 'mainnet';
  contractAddress: string;       // The Provenance Certificate Contract address (0x...)
  certificateId: string;         // Unique ID generated by the smart contract
  transactionHash: string;       // Hash of the minting transaction on BOT Chain
  blockNumber: number;           // The BOT Chain block where this was minted
  ledgerSequence?: number;
  
  mintedAt: Date;                // Blockchain timestamp
  createdAt: Date;
  updatedAt: Date;
}

const CertificateSchema: Schema = new Schema(
  {
    verificationJobId: {
      type: Schema.Types.ObjectId,
      ref: 'VerificationJob',
      required: true,
      unique: true, // One job = One certificate
    },
    assetId: {
      type: Schema.Types.ObjectId,
      ref: 'Asset',
      required: true,
    },
    manifestId: {
      type: Schema.Types.ObjectId,
      ref: 'Manifest',
      required: true,
    },
    creatorId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    botChainNetwork: {
      type: String,
      enum: ['testnet', 'mainnet'],
      required: true,
      default: 'testnet',
    },
    stellarNetwork: {
      type: String,
      enum: ['testnet', 'mainnet'],
      default: 'testnet',
    },
    contractAddress: {
      type: String,
      required: true,
    },
    certificateId: {
      type: String,
      required: true,
      unique: true,
      index: true,
    },
    transactionHash: {
      type: String,
      required: true,
      index: true,
    },
    blockNumber: {
      type: Number,
      required: true,
      default: 0,
    },
    ledgerSequence: {
      type: Number,
      default: 0,
    },
    mintedAt: {
      type: Date,
      required: true,
    }
  },
  { timestamps: true }
);

export default mongoose.model<ICertificate>('Certificate', CertificateSchema);
